import fs from 'node:fs';
import path from 'node:path';
import {releaseInfo} from './release-info.mjs';
const local=releaseInfo(),mobile=JSON.parse(fs.readFileSync('www/release.json','utf8'));
if(local.sourceHash!==mobile.sourceHash||local.buildNumber!==mobile.buildNumber)throw Error('The iPhone assets were built from different source.');
if(process.argv[2]&&releaseInfo(path.resolve(process.argv[2])).sourceHash!==local.sourceHash)throw Error('The Sites mirror differs from the canonical source.');
const origin='https://scripture-lens.kvn-mcgwn.chatgpt.site';
const response=await fetch(origin+'/release.json',{cache:'no-store',signal:AbortSignal.timeout(15000)});
if(!response.ok)throw Error('The website does not expose release information yet.');
const live=await response.json();
if(live.sourceHash!==local.sourceHash||live.buildNumber!==local.buildNumber)throw Error('The live website differs from this iPhone release.');
console.log('VERIFIED: live website, mobile assets'+(process.argv[2]?', Sites mirror':'')+' and canonical source match build '+local.buildNumber+' · '+local.sourceHash.slice(0,12));

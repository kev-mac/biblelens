import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readerMemberships} from './reader-memberships.mjs';
import {addUX13Events} from './ux13-content.mjs';
const read=file=>JSON.parse(fs.readFileSync(file,'utf8'));
const stories=addUX13Events(read('data/stories.json')),commandments=read('data/commandments-catalog.json').records,books=read('data/books.json'),chapters=read('data/chapters.json');
const index=readerMemberships(stories,commandments,books,chapters);
assert(index['0:1'][4].stories.some(s=>s.title==='The Creation'));
assert(index['0:2'][3].stories.some(s=>s.title==='The Creation'),'cross-chapter end included');
assert(!index['0:2']?.[4]?.stories.some(s=>s.title==='The Creation'),'verse after end excluded');
assert(index['0:7'][1].stories.some(s=>s.title==='Noah and the Flood'),'middle chapter included');
assert(index['1:20'][2].commandments.includes('P1'));
assert(index['4:10'][20].commandments.includes('P7'),'additional commandment source reference included');
assert(!index['0:1'][4].commandments.length,'unrelated verse is not a commandment');
assert(!Object.values(index).flatMap(Object.values).some(m=>m.stories.some(s=>s.title==='Parallel Accounts in Genesis')));
const codes=new Set(Object.values(index).flatMap(Object.values).flatMap(m=>m.commandments));
assert.equal(codes.size,613,'all 613 commandments mapped');
const test=readerMemberships([{book:'Genesis',stories:[{title:'Overlap',passage:'Genesis 1:1-2',passages:['Genesis 1:1-2','Genesis 1:2-3'],cross_references:['Genesis 2:1']}]}],[],books,chapters);
assert.equal(test['0:1'][2].stories.length,1,'overlapping source ranges deduplicated');
assert(!test['0:2'],'supporting reference is not a membership');
assert.equal(test['0:1'][2].stories[0].href,'#stories/genesis/overlap');
const workspace=fs.readFileSync('src/workspace.js','utf8');
assert(workspace.includes("label.textContent='TAGGING'"));
assert(workspace.includes('membershipTagsHtml(reading.memberships?.[verse.n])'));
assert(workspace.includes('if(!evidenceVisible)break;'),'tag visibility remains controlled by TAGGING');
const context={esc:value=>String(value).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;')};
vm.createContext(context);
vm.runInContext(workspace.slice(workspace.indexOf(' function membershipTagsHtml('),workspace.indexOf(' function evidenceSummaryHtml(')),context);
assert.equal(context.membershipTagsHtml(undefined),'');
assert.equal(context.membershipTagsHtml({stories:[],commandments:[]}),'');
const html=context.membershipTagsHtml({stories:[{title:'<img src=x>',href:'#stories/genesis/a" onclick="bad'}],commandments:['P1','P2']});
assert(!html.includes('<img'));assert(html.includes('&lt;img src=x&gt;'));
assert.equal(html.split('>COMMANDMENT</span>').length-1,1,'multiple commandments share one tag');
assert(html.includes('P1, P2'));
console.log('Reader membership tags: story boundaries, overlap, cross references and all 613 commandments passed.');

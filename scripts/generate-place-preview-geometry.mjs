// Rebuild the compact, local geographical context used by Places cards.
// The source is Natural Earth 5.1.2, public domain; see atlas-land-provenance.json.
import fs from 'node:fs';
const source=JSON.parse(fs.readFileSync('src/data/atlas-land.json','utf8'));
const bounds=[-24,-4,100,64]; // Includes every current reference point and its preview.
function clip(ring){
 let points=ring;
 for(const [axis,bound,sign] of [[0,bounds[0],1],[0,bounds[2],-1],[1,bounds[1],1],[1,bounds[3],-1]]){
  const output=[];
  for(let i=0;i<points.length;i++){const a=points[i],b=points[(i+1)%points.length],ai=(a[axis]-bound)*sign>=0,bi=(b[axis]-bound)*sign>=0;if(ai)output.push(a);if(ai!==bi){const t=(bound-a[axis])/(b[axis]-a[axis]);output.push([a[0]+(b[0]-a[0])*t,a[1]+(b[1]-a[1])*t]);}}
  points=output;if(!points.length)break;
 }
 return points;
}
function distance(p,a,b){const x=b[0]-a[0],y=b[1]-a[1],t=Math.max(0,Math.min(1,((p[0]-a[0])*x+(p[1]-a[1])*y)/(x*x+y*y||1)));return Math.hypot(p[0]-a[0]-x*t,p[1]-a[1]-y*t);}
function simplify(points){
 if(points.length<3)return points;
 let index=0,max=0;for(let i=1;i<points.length-1;i++){const d=distance(points[i],points[0],points.at(-1));if(d>max){max=d;index=i;}}
 return max>.015?[...simplify(points.slice(0,index+1)).slice(0,-1),...simplify(points.slice(index))]:[points[0],points.at(-1)];
}
const features=source.features.flatMap(feature=>(feature.geometry.type==='MultiPolygon'?feature.geometry.coordinates:[feature.geometry.coordinates]).map(polygon=>{
 const rings=polygon.map(clip).filter(r=>r.length>2).map(r=>simplify([...r,r[0]]).map(p=>p.map(n=>+n.toFixed(4)))).filter(r=>r.length>=4);
 if(!rings.length)return null;
 const points=rings.flat();return {water:feature.properties.water,bbox:[Math.min(...points.map(p=>p[0])),Math.min(...points.map(p=>p[1])),Math.max(...points.map(p=>p[0])),Math.max(...points.map(p=>p[1]))],rings};
})).filter(Boolean);
fs.writeFileSync('src/data/atlas-preview-land.js','// Natural Earth 5.1.2, public domain. Generated by scripts/generate-place-preview-geometry.mjs.\nexport const atlasPreviewLand='+JSON.stringify(features)+';\n');
console.log(`Generated ${features.length} geographical shapes for Places previews.`);
